"""
The reference-feature model breseq annotates against.

Both loaders -- GenBank via Biopython, and breseq's own GFF3 -- build these same
objects, so the annotator never has to care which format a reference arrived in.

Coordinates are 1-based inclusive throughout, like breseq and like the GD format,
not Biopython's 0-based half-open.
"""

from mutint_import.annotate.codon_tables import DEFAULT_TRANSLATION_TABLE

# Separators that must not appear inside a feature name or locus tag, because
# annotation joins lists on them. reference_sequence.cpp:29-57
INTERGENIC_SEPARATOR = '/'
GENE_LIST_SEPARATOR = ','
MULTIPLE_SEPARATOR = '|'

# reference_sequence.cpp:711-773 -- only these become "genes" for annotation.
# Plain `gene` features are deliberately excluded; breseq annotates against the
# CDS/RNA features, and counting both would double every gene. `tmRNA` joined the list
# in October 2026, here and in breseq's `is_gene()` the same day: a transcribed locus
# with a locus tag like any tRNA, so a mutation in it is noncoding, not intergenic.
GENE_TYPES = frozenset(('CDS', 'rRNA', 'tRNA', 'ncRNA', 'tmRNA', 'RNA'))
REPEAT_TYPES = frozenset(('repeat_region', 'mobile_element'))

# flag_pseudo() is a no-op for these. reference_sequence.h:528-537
NEVER_PSEUDO_TYPES = frozenset(('region', 'source', 'repeat_region'))

# Attributes a loader interprets -- ours, or breseq's ReadGFF -- and so never kept as a
# feature's *extra* attribute: under one of these names a GenBank's `/accession` or a
# third-party GFF3's `product=` would be read back as the locus tag or the product on
# reload. `translation` is derived from the sequence and regenerated by the export;
# `Parent` and `gbkey` are NCBI GFF3 structure with no GenBank counterpart. Applied by
# both loaders, so a model reads the same whichever format it came from.
UNSTORABLE_ATTRIBUTES = frozenset((
    'Alias', 'ID', 'Name', 'Note', 'Pseudo', 'pseudo', 'transl_table',
    'indeterminate_coordinate', 'accession', 'locus_tag', 'gene', 'product',
    'translation', 'Is_circular', 'Parent', 'gbkey',
))

# NCBI's GFF3 spelling of a GenBank qualifier, stored under GenBank's name so the export
# writes the qualifier the file would have had.
ATTRIBUTE_RENAMES = {'Dbxref': 'db_xref'}

DEFAULT_REPEAT_NAME = 'repeat_region'
DEFAULT_REPEAT_PRODUCT = 'repeat region'
INSERTION_SEQUENCE_PREFIX = 'insertion sequence:'

_COMPLEMENT = str.maketrans('ACGTacgtNn', 'TGCAtgcaNn')


def reverse_complement(sequence):
    return sequence.translate(_COMPLEMENT)[::-1]


def make_safe(name):
    """reference_sequence.cpp:139-160 -- keep list separators out of names."""
    for separator in (INTERGENIC_SEPARATOR, MULTIPLE_SEPARATOR, GENE_LIST_SEPARATOR):
        name = name.replace(separator, '_')
    return name


# reference_sequence.cpp `safe_seq_id_name_characters`: the only characters breseq keeps in
# a seq id. ASCII only, as breseq's is: it carried a Unicode minus sign for years, and as a
# byte set that admitted other characters sharing one of its bytes, half-rewritten.
SAFE_SEQ_ID_CHARACTERS = frozenset(
    'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz1234567890._-+')


def safe_seq_id(name):
    """reference_sequence.h `safe_seq_id_name` -- the seq id breseq will call this contig.

    breseq rewrites every seq id it loads: a character outside `SAFE_SEQ_ID_CHARACTERS`
    becomes `_`, runs of `__` collapse to one (they are its junction divider), and leading
    and trailing `_` are dropped. Releases before the fix in October 2026 applied that to
    `##sequence-region` lines and FASTA headers but **not** to column 1 of a GFF3 feature
    row, so a stored GFF3 naming a contig `P-Ant1_(_ColE1` verbatim made breseq register
    two contigs, one of them with no sequence, and refuse the reference. Storing the safe
    form keeps the stored GFF3 loadable by every release and the seq ids in breseq's own
    `.gd` output equal to the stored ones.

    `breseq CONVERT-REFERENCE --list-seq-ids` prints breseq's own answer, and
    `test_safe_seq_id.BreseqConformanceTestCase` holds this port to it wherever breseq is
    installed. Raises ValueError where breseq asserts: a name with no valid character.
    """
    safe = ''.join(c if c in SAFE_SEQ_ID_CHARACTERS else '_' for c in name)
    while '__' in safe:
        safe = safe.replace('__', '_')
    safe = safe.strip('_')
    if not safe:
        raise ValueError('Seq id %r contains no valid characters' % (name,))
    return safe


def trim_repeat_name(name):
    """
    E. coli mobile_element names carry a prefix and a copy suffix that breseq
    strips so that IS186B and IS186 are the same repeat family.
    reference_sequence.cpp:2418-2434
    """
    position = name.find(INSERTION_SEQUENCE_PREFIX)
    if position != -1:
        # breseq passes (pos, pos+19) to std::string::erase, which is
        # (index, count) -- so it removes the prefix when it is at the front and
        # overshoots otherwise. Reproduced rather than corrected.
        name = name[:position] + name[position + position + len(INSERTION_SEQUENCE_PREFIX):]

    first_digit = next((i for i, c in enumerate(name) if c.isdigit()), -1)
    if first_digit != -1:
        after_digits = next(
            (i for i in range(first_digit, len(name)) if not name[i].isdigit()), -1)
        if after_digits != -1:
            name = name[:after_digits]
    return name


class FeatureLocation(object):
    """One sublocation of a feature. 1-based inclusive."""

    __slots__ = ('start_1', 'end_1', 'strand', 'start_is_indeterminate',
                 'end_is_indeterminate', 'feature')

    def __init__(self, start_1, end_1, strand,
                 start_is_indeterminate=False, end_is_indeterminate=False, feature=None):
        self.start_1 = start_1
        self.end_1 = end_1
        self.strand = strand
        self.start_is_indeterminate = start_is_indeterminate
        self.end_is_indeterminate = end_is_indeterminate
        self.feature = feature

    def is_top_strand(self):
        return self.strand == 1

    def distance_to_position(self, position_1):
        """0 when the position falls inside this location. reference_sequence.h:292-298"""
        if position_1 < self.start_1:
            return self.start_1 - position_1
        if position_1 > self.end_1:
            return position_1 - self.end_1
        return 0

    def stranded_start_is_indeterminate(self):
        """reference_sequence.h:236-242 -- which end is 5' depends on the strand."""
        return self.start_is_indeterminate if self.strand == 1 else self.end_is_indeterminate

    def stranded_end_is_indeterminate(self):
        return self.end_is_indeterminate if self.strand == 1 else self.start_is_indeterminate

    def sort_key(self):
        return (self.start_1, self.end_1)

    def __repr__(self):
        return 'FeatureLocation(%d..%d, strand=%d)' % (self.start_1, self.end_1, self.strand)


class Feature(object):
    """A feature of the reference, with its sublocations in 5'->3' order.

    A gene (CDS/RNA) or a repeat is what annotation reads; any other type a file carries --
    `regulatory`, `misc_feature`, a `gene` with no CDS under it -- is kept as well,
    in `features` but never in a contig's gene or repeat lists, so the file comes back out
    whole without the annotator seeing anything it did not before.

    `attributes` is `{key: [values]}`: everything the loader read that fed no field here,
    in the file's order -- a GenBank's `/db_xref`, `/old_locus_tag`, `/protein_id`, `/note`,
    `/codon_start`; a GFF3's extra attributes. The model does not interpret them; the stored
    GFF3 carries them and the GenBank export writes them back, which is also where an
    analysis that wants one reads it from.
    """

    def __init__(self, feature_type, name='', product='', locus_tag='',
                 pseudogene=False, translation_table=DEFAULT_TRANSLATION_TABLE,
                 attributes=None):
        self.type = feature_type
        self.name = name
        self.product = product
        self.locus_tag = locus_tag
        self.pseudogene = pseudogene
        self.translation_table = translation_table
        self.locations = []
        self.attributes = dict(attributes) if attributes else {}

    def is_gene(self):
        return self.type in GENE_TYPES

    def is_repeat(self):
        return self.type in REPEAT_TYPES

    def flag_pseudo(self):
        if self.type in NEVER_PSEUDO_TYPES:
            return
        self.pseudogene = True

    def get_locus_tag(self):
        return self.locus_tag

    def start_is_indeterminate(self):
        """Feature-level: the 5' end of the first sublocation. reference_sequence.h:557-572"""
        if not self.locations:
            return False
        return self.locations[0].stranded_start_is_indeterminate()

    def end_is_indeterminate(self):
        if not self.locations:
            return False
        return self.locations[-1].stranded_end_is_indeterminate()

    def get_length(self):
        """Spliced length, summed over sublocations. reference_sequence.h:551-558"""
        return sum(loc.end_1 - loc.start_1 + 1 for loc in self.locations)

    def get_nucleotide_sequence(self, annotated_sequence):
        """Spliced and strand-oriented, so it reads 5'->3' in the gene's own frame."""
        return ''.join(
            annotated_sequence.get_stranded_sequence_1(loc.strand, loc.start_1, loc.end_1)
            for loc in self.locations)

    def genomic_position_to_index_strand_1(self, position_1):
        """
        Map a genomic position to a 1-based index into the spliced, strand-oriented
        gene sequence. reference_sequence.cpp:114-135

        When the position is not inside the feature, breseq falls through leaving
        index == the gene length and strand == 0. Callers test `index != 0` as
        their found-check, so that fallthrough is load-bearing; do not "fix" it.
        """
        index_1 = 0
        for loc in self.locations:
            if loc.start_1 <= position_1 <= loc.end_1:
                if loc.strand == 1:
                    index_1 += position_1 - loc.start_1 + 1
                else:
                    index_1 += loc.end_1 - position_1 + 1
                return index_1, loc.strand
            index_1 += loc.end_1 - loc.start_1 + 1
        return index_1, 0

    def __repr__(self):
        return 'Feature(%s %s)' % (self.type, self.name)


def _span(feature):
    """(low, high, strand) over every sublocation -- how a GenBank `gene` is matched to
    the CDS or RNA it is the locus of, whatever either one's splicing."""
    return (min(loc.start_1 for loc in feature.locations),
            max(loc.end_1 for loc in feature.locations),
            feature.locations[0].strand)


def _has_symbol(feature):
    return bool(feature.name) and feature.name != 'unknown' and feature.name != feature.locus_tag


def fold_gene_features(features):
    """`features` with each `gene` folded into the feature at its coordinates.

    A GenBank locus is normally two features, a `gene` and a CDS (or RNA) over the same
    span. breseq annotates against the CDS and ignores the gene, so the stored form keeps
    one row per locus -- but the gene is where some files put the symbol, and where NCBI
    puts `old_locus_tag` and `db_xref` as well. So the gene's symbol and locus tag fill a
    child that has none, every attribute the child lacks is copied onto it, and the gene
    row goes. A gene with no feature at its span is kept as it is, a `gene` row, so the
    file still says it was there. A gene type is preferred as the child over any other kept
    type at the same span; repeats are never a child.
    """
    genes = [f for f in features if f.type == 'gene' and f.locations]
    if not genes:
        return list(features)
    by_span = {}
    for feature in features:
        if feature.type == 'gene' or feature.is_repeat() or not feature.locations:
            continue
        by_span.setdefault(_span(feature), []).append(feature)

    folded = set()
    for gene in genes:
        candidates = by_span.get(_span(gene)) or []
        child = next((f for f in candidates if f.is_gene()), None) \
            or next(iter(candidates), None)
        if child is None:
            continue
        if _has_symbol(gene) and not _has_symbol(child):
            child.name = gene.name
        if gene.locus_tag and not child.locus_tag:
            child.locus_tag = gene.locus_tag
            if not child.name or child.name == 'unknown':
                child.name = gene.locus_tag
        for key, values in gene.attributes.items():
            child.attributes.setdefault(key, list(values))
        folded.add(id(gene))
    return [f for f in features if id(f) not in folded]


class AnnotatedSequence(object):
    """One reference contig: its sequence, its features, and the record's own facts.

    `circular` is tri-state: True or False when the file said (a GenBank LOCUS topology,
    a GFF3 `region` row's `Is_circular`), None when it did not -- a bare FASTA, or a
    GenBank whose LOCUS line leaves the field blank. The renderer writes nothing for
    None, so "unknown" survives a round trip rather than hardening into "linear".
    """

    def __init__(self, seq_id, sequence, circular=None, metadata=None):
        self.seq_id = seq_id
        self.sequence = sequence
        self.circular = circular
        # `{key: [values]}` about the record rather than any feature: a GenBank's
        # DEFINITION (as `Note`, which is what breseq reads a region row's Note as),
        # organism, taxonomy, comment, date, and the `source` feature's qualifiers. The
        # stored GFF3 carries it on the contig's `region` row and the GenBank export
        # writes the header and the source feature back from it.
        self.metadata = dict(metadata) if metadata else {}
        self.features = []
        self.gene_locations = []
        self.repeat_locations = []

    def __len__(self):
        return len(self.sequence)

    def get_sequence_1(self, start_1, end_1):
        return self.sequence[start_1 - 1:end_1]

    def get_stranded_sequence_1(self, strand, start_1, end_1):
        subsequence = self.get_sequence_1(start_1, end_1)
        return subsequence if strand == 1 else reverse_complement(subsequence)

    def update_feature_lists(self):
        """reference_sequence.cpp:711-773"""
        self.gene_locations = []
        self.repeat_locations = []
        kept = []

        for feature in self.features:
            if feature.start_is_indeterminate() and feature.end_is_indeterminate():
                feature.flag_pseudo()
            if not feature.locations:
                continue
            kept.append(feature)

            if feature.is_repeat():
                # breseq ignores repeats with complex locations rather than
                # guessing which sublocation the mobile element really is.
                if len(feature.locations) == 1:
                    self.repeat_locations.extend(feature.locations)
            elif feature.is_gene():
                self.gene_locations.extend(feature.locations)

        self.features = kept
        # Stable sort on (start, end). Order matters: get_overlapping_feature()
        # returns the LAST match, and gene name lists follow this order.
        self.gene_locations.sort(key=FeatureLocation.sort_key)
        self.repeat_locations.sort(key=FeatureLocation.sort_key)


class LoadedReferenceSequences(object):
    """All contigs of a reference, parsed and keyed by seq id.

    **`Loaded` distinguishes it from `mutint_sample.models.ReferenceSequences`**, the row
    recording that an experiment has a reference and where its files are. This is what you
    get by *reading* those files: sequence and features in memory, for the annotator and for
    the mutation editor's validator. Nothing here is stored, and one is built from the other.
    """

    def __init__(self):
        self.sequences = {}
        # `(original, safe)` for every contig whose name `safe_seq_id` changed on loading,
        # so the caller can tell the uploader. Empty for a file breseq would load as is.
        self.renamed = []

    def __contains__(self, seq_id):
        return seq_id in self.sequences

    def breseq_name(self, original):
        """`safe_seq_id(original)`, recorded on `renamed` when it differs.

        Two contigs of one file collapsing onto one safe name is refused rather than
        merged: `a(b` and `a)b` are two sequences, and `add` would keep only the second.
        """
        safe = safe_seq_id(original)
        if safe != original:
            if safe in self.sequences:
                raise ValueError(
                    'Seq ids %r and %r are both %r once made safe for breseq; rename '
                    'one of them' % (original, self.sequences[safe].seq_id, safe))
            self.renamed.append((original, safe))
        return safe

    def __getitem__(self, seq_id):
        return self.sequences[seq_id]

    def __iter__(self):
        return iter(self.sequences)

    def seq_ids(self):
        return list(self.sequences)

    def get_sequence_1(self, seq_id, start_1, end_1):
        return self.sequences[seq_id].get_sequence_1(start_1, end_1)

    def add(self, annotated_sequence):
        """
        Register a contig under its id, exactly as written.

        A deliberate divergence from breseq, which trims the version suffix off an
        accession when matching GD seq_ids so that `NC_000913.3` and `NC_000913`
        resolve to the same contig. breseq annotates one run against one reference,
        where that is a convenience. MutInt holds many experiments side by side and
        two of them may legitimately be against different versions of the same
        accession; conflating those would annotate a mutation against the wrong
        genome and say nothing about it. Names are matched exactly, and a .gd whose
        seq_ids are not the reference's is refused at import instead -- see
        ``mutint_import.reference_store.known_seq_ids``.
        """
        self.sequences[annotated_sequence.seq_id] = annotated_sequence

    def repeat_family_sequence(self, repeat_name, strand):
        """
        The consensus sequence of a repeat family, oriented to `strand`.

        breseq (reference_sequence.cpp:2804-2956) picks the most common sequence
        among copies, falling back to the most common length. Used only to fill
        MOB `repeat_size`, which mutation_size_change needs.
        """
        copies = []
        for annotated_sequence in self.sequences.values():
            for location in annotated_sequence.repeat_locations:
                feature = location.feature
                if feature.name != repeat_name or feature.pseudogene:
                    continue
                copies.append((
                    annotated_sequence.get_stranded_sequence_1(
                        location.strand, location.start_1, location.end_1),
                    location.strand,
                ))
        if not copies:
            return ''

        counts = {}
        for sequence, _ in copies:
            counts[sequence] = counts.get(sequence, 0) + 1
        best_sequence, best_count = max(counts.items(), key=lambda kv: kv[1])
        if best_count > 1:
            picked = next(c for c in copies if c[0] == best_sequence)
        else:
            length_counts = {}
            for sequence, _ in copies:
                length_counts[len(sequence)] = length_counts.get(len(sequence), 0) + 1
            best_length = max(length_counts.items(), key=lambda kv: kv[1])[0]
            picked = next(c for c in copies if len(c[0]) == best_length)

        picked_sequence, picked_strand = picked
        if strand not in (1, -1):
            return picked_sequence
        return picked_sequence if strand == picked_strand else reverse_complement(picked_sequence)

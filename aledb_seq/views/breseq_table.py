"""One sample's mutations, laid out the way breseq's own report lays them out.

`/mutations` pivots an experiment across every sample, which is what you want for
comparing lineages and not what you want for reading one sample. This is the other
view of the same data: a single resequencing run in breseq's column order and
colouring, with a picker to move between samples.

It renders server-side rather than feeding DataTables a JSON blob, because the
cell markup *is* breseq's -- generated by `aledb_import.annotate.display`, which
is the same code that produced the HTML in the breseq report the sample came from.
"""

import collections
import logging
import time

from django.http import HttpResponse
from django.template import loader
from django.urls import reverse

import aledb_seq.views.common
from aledb_common.logger import join_extras, user_extra
from aledb_common.util import get_user_context
from aledb_experiment.models import AleExperiment
from aledb_experiment.permissions import can_edit_project
from aledb_filter.util import filter_observed_mutations
from aledb_filter.view_filter import get_view_filter
from aledb_seq.breseq_report import build_rows, is_population
from aledb_seq.models import ExperimentReference, ObservedMutation
from aledb_experiment.ancestor import ancestral_mutation_ids, describe_ancestor
from aledb_seq.util import get_reseq_ordered_dict

logger = logging.getLogger(__name__)

REQUEST_RESEQ_ID = "reseq_id"


def breseq_table(request):
    context = get_user_context(request.user)
    try:
        started = time.time()
        experiment = aledb_seq.views.common.get_ale_experiment(request)
        ale_number = aledb_seq.views.common.get_ale_id(request)
        sample_type = aledb_seq.views.common.get_sample_type(request)

        # `include_ancestor=True`, unlike every other reading page. This one shows a single
        # sample at a time, so there is nothing here for an ancestral mutation to contaminate
        # -- and hiding the ancestor from the only picker that could reach it made it
        # unreachable rather than merely excluded. It is listed first and tinted; the
        # analyses that aggregate across samples still leave it out.
        reseq_dict = get_reseq_ordered_dict(experiment.ale_id, ale_number,
                                            sample_type, request, include_ancestor=True)
        reseq_dict = _ancestor_first(reseq_dict, experiment.ancestor_id)
        reseq = _selected_reseq(request, reseq_dict, experiment)

        view_filter = get_view_filter(request, experiment.ale_id)
        # Resolved once for the whole page: the tint is a membership test per rendered row.
        ancestral_ids = ancestral_mutation_ids(experiment.ale_id)
        rows = (_rows_for(experiment, reseq, view_filter, ancestral_ids)
                if reseq is not None else [])

        context.update(experiment.experiment_context())
        context.update({
            "ales": aledb_seq.views.common.get_aleid_ale_id_list(experiment.ale_id),
            "ale_no": ale_number,
            "ale_experiment_name": experiment.name,
            "ale_project_name": experiment.project.name if experiment.project else "",
            "ale_project_id": experiment.project_id,
            "sample_type": sample_type,
            "reseq_list": list(reseq_dict.values()),
            "selected_reseq": reseq,
            "selected_reseq_id": reseq.id if reseq is not None else None,
            "is_population": is_population(reseq),
            "is_ancestor": reseq is not None and reseq.id == experiment.ancestor_id,
            "ancestral_count": sum(1 for row in rows if row["ancestral"]),
            # The name and pk, so the legend can link the tinted rows to the sample they
            # came from. `describe_ancestor` is what the summary line under every other
            # table already uses, rather than a second way of spelling the same thing.
            "ancestor": describe_ancestor(experiment.ale_id),
            "rows": rows,
            "unannotated_count": sum(1 for row in rows if not row["annotated"]),
            "reference": _reference(experiment),
            "title": "%s mutations" % experiment.name,
            "template_header": "Mutations",
            "can_edit": can_edit_project(request.user, experiment.project),
        })

        logger.info("samples",
                    extra=join_extras(user_extra(request),
                                      {"time taken": time.time() - started, "rows": len(rows)}))
        template = loader.get_template("breseq_table/breseq_table.html")
        return HttpResponse(template.render(context, request), content_type="text/html")
    except AleExperiment.DoesNotExist:
        return aledb_seq.views.common.no_experiment_selected(
            request, context, logger, "samples")
    except Exception as error:
        logger.exception("samples broke", extra=user_extra(request))
        context["err_message"] = str(error)
        template = loader.get_template("500.html")
        return HttpResponse(template.render(context, request), content_type="text/html")


def _ancestor_first(reseq_dict, ancestor_id):
    """Move the designated ancestor to the top of the picker.

    It is what the other samples are read against, so it belongs at the top rather than
    wherever A/F/I/R ordering happens to put it -- for the LTEE that is a lucky first anyway,
    but only because its ancestor is filed under an ALE that sorts early.

    Order only. The *default* selection stays the first non-ancestor sample (see
    `_selected_reseq`), so opening Mutations still lands on evolved data.
    """
    if ancestor_id is None or ancestor_id not in reseq_dict:
        return reseq_dict
    ordered = collections.OrderedDict()
    ordered[ancestor_id] = reseq_dict[ancestor_id]
    for key, value in reseq_dict.items():
        if key != ancestor_id:
            ordered[key] = value
    return ordered


def _selected_reseq(request, reseq_dict, experiment):
    """The requested sample; failing that the first one that is not the ancestor.

    The ancestor is listed, and listed first, but is not what the page opens on: this view is
    read as "what evolved in this sample", and defaulting to the one sample where the answer
    is "nothing, by definition" is a poor first thing to show. It is one click away in the
    picker, which is the point of putting it there.

    The lookup still falls back to a scoped query. `reseq_dict` honours the ALE, sample-type
    and tag filters, so a requested id can legitimately be missing from it -- and without the
    fallback a link to a filtered-out sample would quietly render a *different* one, which is
    the worst available outcome because the page would look entirely normal while showing the
    wrong thing. Scoped to the experiment, so it is not a way around anything.
    """
    requested = request.GET.get(REQUEST_RESEQ_ID)
    if requested:
        try:
            reseq_id = int(requested)
        except (TypeError, ValueError):
            reseq_id = None
        if reseq_id in reseq_dict:
            return reseq_dict[reseq_id]
        if reseq_id is not None:
            hidden = get_reseq_ordered_dict(experiment.ale_id, include_ancestor=True)
            if reseq_id in hidden:
                return hidden[reseq_id]
    for reseq in reseq_dict.values():
        if reseq.id != experiment.ancestor_id:
            return reseq
    # An experiment whose only sample is the ancestor: show it rather than nothing.
    for reseq in reseq_dict.values():
        return reseq
    return None


def _rows_for(experiment, reseq, view_filter=None, ancestral_ids=frozenset()):
    """This sample's rows, ancestor included.

    Deliberately the raw observation queryset. Every page that analyses the data subtracts the
    designated ancestor; this one tints those rows instead, because it is a view of what
    breseq called in one sample rather than a conclusion drawn from it.
    """
    observed = filter_observed_mutations(
        ObservedMutation.objects.filter(sequencing_experiment=reseq).select_related("mutation"),
        view_filter=view_filter)
    # filter_observed_mutations orders across samples; within one sample breseq
    # orders by reference then position.
    observed.sort(key=lambda o: (o.mutation.reseq_reference or "", o.mutation.position))
    return build_rows(observed, browse_url=_browse_url(reseq),
                      ancestral_mutation_ids=ancestral_ids)


def _browse_url(reseq):
    """Link the evidence cell at the alignment, when there is one to look at."""
    if not reseq.bam_stored:
        return None
    return lambda observed: "%s?observed_mut_id=%s" % (
        reverse("browse_mutation"), observed.id)


def _reference(experiment):
    return ExperimentReference.objects.filter(ale_experiment=experiment).first()
